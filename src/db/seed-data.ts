// Surnames whose female form does not follow the suffix rules.
const IRREGULAR_FEMALE_SURNAMES: Record<string, string> = {
  Толстой: "Толстая",
};

export function femaleSurname(male: string): string {
  if (male in IRREGULAR_FEMALE_SURNAMES) {
    return IRREGULAR_FEMALE_SURNAMES[male];
  }
  if (/(ов|ев|ёв|ин|ын)$/.test(male)) {
    return `${male}а`;
  }
  if (/(ский|цкий)$/.test(male)) {
    return `${male.slice(0, -2)}ая`;
  }
  return male;
}

