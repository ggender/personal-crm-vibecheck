export type Gender = "m" | "f";

// Either one text for both genders or [male, female] variants.
export type Gendered = string | readonly [string, string];

export function pickGendered(value: Gendered, gender: Gender): string {
  if (typeof value === "string") {
    return value;
  }
  return gender === "m" ? value[0] : value[1];
}

